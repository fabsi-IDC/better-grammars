    public SecondaryStructureGrammar randomSimpleStep(SecondaryStructureGrammar grammarToImprove){
        Collection<Rule> allRules = grammarToImprove.getAllRules();
         Rule[] allRuleArray = allRules.toArray(new Rule[0]);
         int x = (int) (Math.random() * allRuleArray.length);
         int y = (int) (Math.random() * allPossibleRules.size());
         allRuleArray[x] = allPossibleRules.get(y);
         MyMultimap<NonTerminal, Rule> rules = new MyMultimap<>();
         for(Rule rule : allRuleArray){
             rules.put(rule.left, rule);
         }
         return new SecondaryStructureGrammar(grammarToImprove.name,grammarToImprove.startSymbol,rules);
    }

