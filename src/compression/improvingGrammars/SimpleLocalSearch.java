    //This is the actual local search idk how to name it
    public SecondaryStructureGrammar walker(SecondaryStructureGrammar grammarToImprove) {
        int i = 0;
        RuleProbType model =  RuleProbType.SEMI_ADAPTIVE;
        while (i < maxAttempts) {
            //checks if it is a valid grammar exactly like in RandomGrammarExplorer (lvl1)
            boolean passedlvl1 = true;
            SecondaryStructureGrammar step = randomSimpleStep(grammarToImprove);
            SRFParser<Character> ssParser = new SRFParser<>(step);
            for (List<Terminal<Character>> word : parsableDatasetWords) {
                if (!ssParser.parsable(word)){
                    passedlvl1 = false;
                    break;
                }
            }
            //if it passes lvl 1, we now look if it is a better grammar on lvl2 / small data
            if (passedlvl1) {
                double avgBitsPerBaseSmallDatasetStep = getBitsPerBase(smallDataset, model, step, false);
                double avgBitsPerBaseSmallDatasetGrammarToImprove = getBitsPerBase(smallDataset, model, grammarToImprove, false);
                if(avgBitsPerBaseSmallDatasetStep < avgBitsPerBaseSmallDatasetGrammarToImprove){
                    //if the new Grammar step is better than the GrammarToImprove on level 2
                    double avgBitsPerBaseFullDatasetStep = getBitsPerBase(fullDataset, model, step, true);
                    double avgBitsPerBaseFullDatasetGrammarToImprove = getBitsPerBase(fullDataset, model, grammarToImprove, true);
                    if (avgBitsPerBaseFullDatasetStep < avgBitsPerBaseFullDatasetGrammarToImprove) {
                        // after debugging should be replaced with return grammar and another return after i++ if no better grammar has been found
                        steps ++;
                        return walker(grammarToImprove);
                    }
                }
            }
            i++;
        }

       // System.out.println("best grammar found: "+ grammarToImprove.toString());
       // System.out.println(" ");
       // System.out.println("It only took " + steps + " steps . Jay");
        System.out.println("steps: " + steps);
        return grammarToImprove;
    }
